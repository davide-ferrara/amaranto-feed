#!/usr/bin/env python3
"""Generate native launch colors from lib/theme/app_theme.dart (requires Pillow)."""
import json
import re
from pathlib import Path

from PIL import Image, ImageColor

ROOT = Path(__file__).resolve().parents[1]
PALETTE = (ROOT / 'lib/theme/app_theme.dart').read_text()


def color(name):
    match = re.search(rf'static const {name} = Color\(0xFF([0-9A-Fa-f]{{6}})\)', PALETTE)
    if match is None:
        raise ValueError(f'Missing opaque AppPalette color: {name}')
    return '#' + match[1]


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


res = ROOT / 'android/app/src/main/res'
for suffix, background, top, bottom in [
    ('', color('page'), '#FFFFFF', '#FFFFFF'),
    ('-night', color('darkPage'), '#303030', '#303030'),
]:
    write(res / f'values{suffix}/colors.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/sync_native_theme.py from AppPalette. -->
<resources>
    <color name="brand_background">{background}</color>
    <color name="brand_splash_background">{top}</color>
    <color name="launcher_icon_background">#FFFFFF</color>
    <color name="brand_launch_top">{top}</color>
    <color name="brand_launch_bottom">{bottom}</color>
</resources>
''')

assets = ROOT / 'ios/Runner/Assets.xcassets'
images = []
for dark in [False, True]:
    top = '#303030' if dark else '#FFFFFF'
    bottom = top
    start, end = ImageColor.getrgb(top), ImageColor.getrgb(bottom)
    image = Image.new('RGB', (1, 256))
    image.putdata([
        tuple(round(a + (b - a) * y / 255) for a, b in zip(start, end))
        for y in range(256)
    ])
    directory = assets / 'LaunchBackground.imageset'
    directory.mkdir(parents=True, exist_ok=True)
    filename = 'background-dark.png' if dark else 'background.png'
    image.save(directory / filename, optimize=True)
    spec = {'idiom': 'universal', 'filename': filename}
    if dark:
        spec['appearances'] = [{'appearance': 'luminosity', 'value': 'dark'}]
    images.append(spec)
write(directory / 'Contents.json', json.dumps({
    'images': images, 'info': {'author': 'xcode', 'version': 1},
}, indent=2) + '\n')

for name, light, dark in [
    ('BrandLaunchBackground', '#FFFFFF', '#303030'),
    ('BrandLaunchText', color('amaranto'), '#FFFFFF'),
]:
    variants = []
    for index, value in enumerate([light, dark]):
        red, green, blue = ImageColor.getrgb(value)
        variant = {'idiom': 'universal', 'color': {
            'color-space': 'srgb', 'components': {
                'red': f'0x{red:02X}', 'green': f'0x{green:02X}',
                'blue': f'0x{blue:02X}', 'alpha': '1.000',
            },
        }}
        if index:
            variant['appearances'] = [{'appearance': 'luminosity', 'value': 'dark'}]
        variants.append(variant)
    write(assets / f'{name}.colorset/Contents.json', json.dumps({
        'colors': variants, 'info': {'author': 'xcode', 'version': 1},
    }, indent=2) + '\n')

print('Synced native launch colors and gradients from AppPalette.')
